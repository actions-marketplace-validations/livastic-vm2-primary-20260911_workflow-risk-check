import {analyzeWorkflow} from "./analyzer.mjs";

const $=(id)=>document.getElementById(id);
const input=$("workflow-input");
const size=$("input-size");
const empty=$("results-empty");
const output=$("results-output");
const error=$("results-error");
const status=$("analysis-status");
const summary=$("results-summary");
const list=$("results-list");
const copyStatus=$("copy-status");
const demo = `name: PR build
on: pull_request_target

permissions: write-all

jobs:
  build:
    runs-on: [self-hosted, linux]
    steps:
      - uses: actions/checkout@v4
      - run: npm ci && npm test
`;

let lastReport=null;
function reset({clearInput=false}={}){
  if(clearInput) input.value="";
  output.hidden=true;
  error.hidden=true;
  empty.hidden=false;
  status.textContent="READY";
  lastReport=null;
  copyStatus.textContent="";
  size.textContent=input.value.length.toLocaleString()+" characters";
}
function el(tag,className,text){
  const e=document.createElement(tag);
  if(className)e.className=className;
  if(text!==undefined)e.textContent=text;
  return e;
}
function addText(parent,tag,className,value){
  const element=el(tag,className,value);
  parent.append(element);
  return element;
}
function showError(message){
  empty.hidden=true;
  output.hidden=true;
  error.hidden=false;
  error.textContent=message;
  status.textContent="INVALID YAML";
  lastReport=null;
}
function render(result){
  error.hidden=true;
  empty.hidden=true;
  output.hidden=false;
  status.textContent="CHECK COMPLETE";
  summary.replaceChildren();
  list.replaceChildren();
  const badges=el("div","summary-badges");
  for(const sev of ["high","medium","note"]){
    const chip=el("div","summary-chip "+sev);
    addText(chip,"strong","",String(result.counts[sev]));
    addText(chip,"span","",sev.toUpperCase());
    badges.append(chip);
  }
  summary.append(badges);
  const title = result.findings.length
    ? `${result.findings.length} item${result.findings.length===1?"":"s"} worth reviewing`
    : "No issues detected by these rules";
  addText(summary,"h3","summary-title",title);
  addText(summary,"p","summary-detail",result.events.length ? "Detected trigger(s): "+result.events.join(", ") : "No on: triggers detected. Confirm the workflow is configured correctly.");
  if(!result.findings.length){
    const clear=el("div","all-clear");
    addText(clear,"div","all-clear-icon","✓");
    addText(clear,"p","","No findings from the included static checks. This does not establish that the workflow is secure.");
    list.append(clear);
  } else {
    for(const [i,issue] of result.findings.entries()){
      const card=el("article","finding "+issue.severity);
      const top=el("div","finding-top");
      addText(top,"span","severity "+issue.severity,issue.severity.toUpperCase());
      addText(top,"span","finding-id",issue.id);
      card.append(top);
      addText(card,"h4","",issue.title);
      addText(card,"p","location",issue.where);
      addText(card,"p","finding-description",issue.description);
      const fix=el("div","fix");
      addText(fix,"strong","","SUGGESTED FIX");
      addText(fix,"p","",issue.recommendation);
      card.append(fix);
      if(issue.source){
        const source=el("a","source-link","Reference documentation ↗");
        source.href=issue.source;
        source.target="_blank";
        source.rel="noopener noreferrer";
        card.append(source);
      }
      list.append(card);
    }
  }
}
function scan(){
  copyStatus.textContent="";
  const result=analyzeWorkflow(input.value,"workflow.yml");
  if(result.error){showError(result.error);return;}
  lastReport=result;
  render(result);
}
function markdownReport(result) {
  const lines=[
    "# Workflow Risk Check — static preflight",
    "",
    "Workflow: "+result.file,
    "Triggers: "+(result.events.join(", ")||"not detected"),
    "Findings: "+result.counts.high+" high, "+result.counts.medium+" medium, "+result.counts.note+" note",
    "",
    "Static, heuristic checks only. A passing result does not guarantee security.",
    ""
  ];
  for(const i of result.findings){
    lines.push("## ["+i.severity.toUpperCase()+"] "+i.title, "",
      "Location: `"+i.where+"`",
      "Rule: `"+i.id+"`","",
      i.description,"","Suggested fix: "+i.recommendation,"",
      "Reference: "+i.source,"");
  }
  if(!result.findings.length)lines.push("No selected patterns were detected. Manual security review is still required.","");
  lines.push("Generated by Workflow Risk Check — https://github.com/livastic-vm2-primary-20260911/workflow-risk-check");
  return lines.join("\n");
}
input.addEventListener("input",()=>size.textContent=input.value.length.toLocaleString()+" characters");
input.addEventListener("keydown",evt=>{if((evt.ctrlKey||evt.metaKey)&&evt.key==="Enter"){evt.preventDefault();scan();}});
$("scan-btn").addEventListener("click",scan);
$("sample-btn").addEventListener("click",()=>{input.value=demo;reset();scan();});
$("clear-btn").addEventListener("click",()=>reset({clearInput:true}));
$("file-input").addEventListener("change",async event=>{
 const file=event.target.files?.[0];if(!file)return;
 try{
  if(file.size>240000)throw new Error("File too large. Maximum 240 KB.");
  if(!/\.ya?ml$/i.test(file.name))throw new Error("Choose a .yml or .yaml file.");
  input.value=await file.text();reset();scan();
 }catch(e){showError(String(e.message||e));}
 finally{event.target.value="";}
});
$("copy-report").addEventListener("click",async()=>{
 if(!lastReport)return;
 try {await navigator.clipboard.writeText(markdownReport(lastReport));copyStatus.textContent="Copied!";}
 catch {copyStatus.textContent="Clipboard unavailable here. Try HTTPS or localhost.";}
});
reset();
